"""Generate the project's SYNTHETIC test images and pipeline figures.

    python scripts/generate_samples.py

Writes to assets/samples/ (input images) and docs/images/ (stage-by-stage
figures for the report). Every image is generated by this script with a fixed
random seed - none of it is real camera data or an external dataset.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import cv2  # noqa: E402
import numpy as np  # noqa: E402

from src.vision import (HSVRange, VisionSettings, bgr_to_hsv, find_marker, preprocess,  # noqa: E402
                        process_frame, segment_hsv)

SAMPLES = ROOT / "assets" / "samples"
FIGS = ROOT / "docs" / "images"


def hsv_bgr(h, s=220, v=220):
    return tuple(int(c) for c in cv2.cvtColor(np.uint8([[[h, s, v]]]), cv2.COLOR_HSV2BGR)[0, 0])


def scene(seed, centre, radius=40, hue=60, size=(640, 480), noise=40, specks=30, distractor=True):
    rng = np.random.default_rng(seed)
    w, h = size
    img = np.full((h, w, 3), (45, 35, 35), np.uint8)
    img = cv2.add(img, rng.integers(0, noise, img.shape, dtype=np.uint8))
    for y in range(h):  # soft lighting gradient
        img[y] = np.clip(img[y].astype(int) + int(25 * y / h), 0, 255)
    if distractor:
        cv2.rectangle(img, (60, 340), (150, 430), hsv_bgr(115), -1)       # blue box
        cv2.circle(img, (520, 380), 30, hsv_bgr(0, 30, 200), -1)          # pale, low saturation
    if centre is not None:
        cv2.circle(img, centre, radius, hsv_bgr(hue), -1)
        cv2.circle(img, (centre[0] - 8, centre[1] + 4), radius // 6, hsv_bgr(hue, 120, 255), -1)  # highlight hole
    for _ in range(specks):  # isolated marker-coloured pixels -> removed by opening
        x, y = rng.integers(0, w), rng.integers(0, h)
        img[y, x] = hsv_bgr(hue)
    return img


def label(img, text):
    out = img.copy() if img.ndim == 3 else cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)
    cv2.rectangle(out, (0, 0), (out.shape[1], 22), (0, 0, 0), -1)
    cv2.putText(out, text, (6, 16), cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255, 255, 255), 1, cv2.LINE_AA)
    return out


def main() -> None:
    SAMPLES.mkdir(parents=True, exist_ok=True)
    FIGS.mkdir(parents=True, exist_ok=True)
    manifest = []
    cases = [
        ("synthetic_green_centre.png", 1, (320, 240), 60, "green disc, centre"),
        ("synthetic_green_left.png", 2, (140, 160), 60, "green disc, upper left"),
        ("synthetic_red_right.png", 3, (500, 200), 178, "red disc (hue wraps 180), right"),
        ("synthetic_blue_low.png", 4, (330, 400), 110, "blue disc, bottom"),
        ("synthetic_no_marker.png", 5, None, 60, "no marker, distractors only"),
    ]
    for name, seed, centre, hue, desc in cases:
        img = scene(seed, centre, hue=hue)
        cv2.imwrite(str(SAMPLES / name), img)
        manifest.append({"file": name, "synthetic": True, "seed": seed, "size": [640, 480],
                         "marker_centre_px": list(centre) if centre else None,
                         "marker_radius_px": 40 if centre else None, "marker_hue": hue if centre else None,
                         "description": desc,
                         "marker_selected_expected": hue != 110})
    manifest[3]["note"] = ("Limitation demo: the blue distractor box is larger than the blue marker, "
                           "so the largest-blob rule selects the box instead of the marker.")
    # moving sequence for temporal tests
    seq = SAMPLES / "sequence"
    seq.mkdir(exist_ok=True)
    for i in range(10):
        c = (120 + i * 40, 240 + int(60 * np.sin(i / 3)))
        cv2.imwrite(str(seq / f"frame_{i:02d}.png"), scene(100 + i, c))
        manifest.append({"file": f"sequence/frame_{i:02d}.png", "synthetic": True, "seed": 100 + i,
                         "size": [640, 480], "marker_centre_px": list(c), "marker_radius_px": 40,
                         "marker_hue": 60, "description": "moving green disc sequence",
                         "marker_selected_expected": True})
    (SAMPLES / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    # ---- stage-by-stage figure from the first sample (same code as the game)
    img = scene(1, (320, 240))
    s = VisionSettings(hsv_range=HSVRange.preset("green"), mirror=False, extras=True)
    small = preprocess(img, s.process_size, 0)
    blurred = preprocess(img, s.process_size, s.blur_ksize)
    hsv = bgr_to_hsv(blurred)
    res = process_frame(img, s)
    raw_unblurred = segment_hsv(bgr_to_hsv(small), s.hsv_range)
    track = res.frame.copy()
    d = res.detection
    x, y, w, h = d.bbox
    cv2.rectangle(track, (x, y), (x + w, y + h), (0, 255, 255), 1)
    cv2.drawMarker(track, (int(d.x), int(d.y)), (255, 0, 255), cv2.MARKER_CROSS, 14, 2)
    hue_vis = cv2.applyColorMap((hsv[..., 0].astype(np.float32) * 255 / 179).astype(np.uint8), cv2.COLORMAP_HSV)
    from src.vision import clean_mask
    morph_only = clean_mask(raw_unblurred, s.kernel_size, s.open_iter, s.close_iter)
    tiles = [label(small, "1 input (downscaled)"), label(blurred, "2 Gaussian blur 5x5"),
             label(hue_vis, "3 HSV: hue channel"), label(raw_unblurred, "4 threshold, no blur: specks"),
             label(morph_only, "5 opening+closing removes them"), label(res.raw_mask, "6 threshold after blur"),
             label(track, f"7 centroid ({d.x:.1f},{d.y:.1f})"), label(res.edges, "8 Canny edges (demo)")]
    grid = np.vstack([np.hstack(tiles[:4]), np.hstack(tiles[4:])])
    cv2.imwrite(str(FIGS / "pipeline_stages.png"), grid)

    # motion figure: track the sequence and draw the trajectory + velocity vectors
    canvas = None
    pts = []
    for i in range(10):
        frame = cv2.imread(str(seq / f"frame_{i:02d}.png"))
        r = process_frame(frame, s)
        if canvas is None:
            canvas = r.frame.copy()
        pts.append((r.detection.x, r.detection.y))
    for i, (px, py) in enumerate(pts):
        cv2.circle(canvas, (int(px), int(py)), 3, (255, 0, 255), -1)
        if i:
            qx, qy = pts[i - 1]
            cv2.arrowedLine(canvas, (int(qx), int(qy)), (int(px), int(py)), (0, 255, 255), 1, tipLength=0.3)
    cv2.imwrite(str(FIGS / "motion_trajectory.png"), cv2.resize(canvas, (640, 480), interpolation=cv2.INTER_NEAREST))
    print(f"wrote {len(manifest)} synthetic samples to {SAMPLES} and figures to {FIGS}")
    found = sum(find_marker(segment_hsv(bgr_to_hsv(preprocess(cv2.imread(str(SAMPLES / m['file'])),
                (320, 240))), HSVRange.preset('green')), 150).found for m in manifest)
    print(f"green preset finds a marker in {found}/{len(manifest)} samples (expected 12: 2 green stills + 10 sequence)")


if __name__ == "__main__":
    main()
